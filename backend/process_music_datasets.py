# ── 2. Data Cleaning & Validation Function ───────────────────────────────────

def clean_and_unify_music_dataset():
    print("\n[Step 1/4] Consolidating raw data sources...")
    
    # Load existing CSV if present
    existing_records = []
    if os.path.exists(OUTPUT_PATH):
        try:
            df_curr = pd.read_csv(OUTPUT_PATH)
            existing_records = df_curr.to_dict('records')
            print(f"  Loaded {len(existing_records)} existing records from spotify_tracks.csv")
        except Exception as e:
            print(f"  Warning: Could not read existing spotify_tracks.csv ({e})")

    # Combine all sources
    try:
        from enrich_music_dataset import KAGGLE_EXTRACTED_TRACKS
    except ImportError:
        try:
            from backend.enrich_music_dataset import KAGGLE_EXTRACTED_TRACKS
        except ImportError:
            KAGGLE_EXTRACTED_TRACKS = []

    all_raw = MASTER_TRACKS + KAGGLE_EXTRACTED_TRACKS + existing_records
    print(f"  Total candidate entries before deduplication: {len(all_raw)}")

    print("\n[Step 2/4] Normalizing schema, cleaning text, and validating audio features...")
    cleaned_rows = []
    seen_keys = set()

    for item in all_raw:
        track_name = str(item.get('track_name', '')).strip()
        artists = str(item.get('artists', '')).strip()
        if not track_name or not artists or track_name.lower() == 'nan':
            continue

        # Normalized deduplication key: title + primary artist
        primary_artist = artists.split(',')[0].strip().lower()
        norm_title = re.sub(r'\(.*?\)|\[.*?\]', '', track_name).strip().lower()
        norm_title = re.sub(r'[^\w\s]', '', norm_title)
        dedup_key = f"{norm_title}::{primary_artist}"

        if dedup_key in seen_keys:
            continue
        seen_keys.add(dedup_key)

        # Generate stable track_id if missing
        track_id = str(item.get('track_id', ''))
        if not track_id or track_id == 'nan':
            clean_token = re.sub(r'\W+', '_', f"{primary_artist}_{norm_title}").lower()
            track_id = f"trk_{clean_token}"[:32]

        album_name = str(item.get('album_name', '')).strip() or "Single"
        genre = str(item.get('track_genre', 'pop')).strip().lower()
        if genre in ['synthpop', 'dance', 'disco']:
            genre = 'pop'
        elif genre in ['alternative', 'hard rock', 'punk']:
            genre = 'rock'
        elif genre in ['ambient', 'chillwave']:
            genre = 'lo-fi'

        # Verified album art fallback
        album_art = str(item.get('album_art', '')).strip()
        if not album_art or not album_art.startswith('http') or album_art == 'nan':
            album_art = 'https://images.unsplash.com/photo-1514525253161-7a46d19cd819?w=600&auto=format&fit=crop&q=80'

        # Safe numeric feature extraction with defaults
        def safe_float(val, default):
            try:
                return float(val) if not pd.isna(val) else default
            except:
                return default

        def safe_int(val, default):
            try:
                return int(val) if not pd.isna(val) else default
            except:
                return default

        popularity = safe_int(item.get('popularity'), 85)
        duration_ms = safe_int(item.get('duration_ms'), 210000)
        explicit = bool(item.get('explicit', False))
        danceability = np.clip(safe_float(item.get('danceability'), 0.60), 0.0, 1.0)
        energy = np.clip(safe_float(item.get('energy'), 0.65), 0.0, 1.0)
        key = safe_int(item.get('key'), 1)
        loudness = np.clip(safe_float(item.get('loudness'), -6.5), -60.0, 0.0)
        mode_val = 1 if safe_int(item.get('mode'), 1) == 1 else 0
        speechiness = np.clip(safe_float(item.get('speechiness'), 0.05), 0.0, 1.0)
        acousticness = np.clip(safe_float(item.get('acousticness'), 0.25), 0.0, 1.0)
        instrumentalness = np.clip(safe_float(item.get('instrumentalness'), 0.01), 0.0, 1.0)
        liveness = np.clip(safe_float(item.get('liveness'), 0.12), 0.0, 1.0)
        valence = np.clip(safe_float(item.get('valence'), 0.50), 0.0, 1.0)
        tempo = np.clip(safe_float(item.get('tempo'), 115.0), 40.0, 250.0)
        time_signature = safe_int(item.get('time_signature'), 4)

        cleaned_rows.append({
            'track_id': track_id,
            'artists': artists,
            'album_name': album_name,
            'track_name': track_name,
            'popularity': popularity,
            'duration_ms': duration_ms,
            'explicit': explicit,
            'danceability': round(danceability, 3),
            'energy': round(energy, 3),
            'key': key,
            'loudness': round(loudness, 2),
            'mode': mode_val,
            'speechiness': round(speechiness, 3),
            'acousticness': round(acousticness, 4),
            'instrumentalness': round(instrumentalness, 5),
            'liveness': round(liveness, 3),
            'valence': round(valence, 3),
            'tempo': round(tempo, 1),
            'time_signature': time_signature,
            'track_genre': genre,
            'album_art': album_art
        })

    df_clean = pd.DataFrame(cleaned_rows)

    # Sort descending by popularity
    df_clean = df_clean.sort_values(by=['popularity', 'track_name'], ascending=[False, True]).reset_index(drop=True)

    print("\n[Step 3/4] Dataset Validation & Statistical Overview:")
    print(f"  * Total Unique Tracks: {len(df_clean)}")
    print(f"  * Unique Artists:      {df_clean['artists'].nunique()}")
    print(f"  * Genres Distribution:")
    for genre, count in df_clean['track_genre'].value_counts().items():
        print(f"      - {genre.title():<14}: {count} tracks")

    print("\n[Step 4/4] Writing unified authoritative dataset to disk...")
    df_clean.to_csv(OUTPUT_PATH, index=False)
    file_size_kb = os.path.getsize(OUTPUT_PATH) / 1024
    print(f"  [OK] Successfully written to: {OUTPUT_PATH} ({file_size_kb:.1f} KB)")
    print("=" * 65)
    print("PIPELINE COMPLETED SUCCESSFULLY: Single clean music dataset generated.")
    print("=" * 65)

if __name__ == "__main__":
    clean_and_unify_music_dataset()
